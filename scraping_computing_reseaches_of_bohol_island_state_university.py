def main():
    if MAILTO == "your-real-email@example.com":
        raise ValueError("Please replace MAILTO with your real email address first.")

    session = build_session()
    unique_keys = set()
    final_rows = []

    for aff_query in AFFILIATION_QUERIES:
        total = get_total_results(session, aff_query, START_YEAR, END_YEAR)
        print(f"\n[COUNT] {aff_query} -> total-results={total}")

        if total == -1:
            print(f"[SKIP] Could not get total results for '{aff_query}'")
            continue

        rows = fetch_crossref_for_affiliation(
            session=session,
            affiliation_query=aff_query,
            start_year=START_YEAR,
            end_year=END_YEAR,
            rows_per_request=ROWS_PER_REQUEST,
        )

        for row in rows:
            key = dedup_key(row)
            if key in unique_keys:
                continue
            unique_keys.add(key)
            final_rows.append(row)

    final_rows.sort(
        key=lambda r: (
            int(r["Year"]) if str(r["Year"]).isdigit() else 0,
            r["CampusMatched"],
            r["ProgramInferred"],
            r["Title"].lower(),
        ),
        reverse=True,
    )

    save_to_csv(OUTPUT_CSV, final_rows)

    print("\n[SUMMARY]")
    print(f"Unique BISU computing-related Crossref records found: {len(final_rows)}")

    campus_counts = {}
    program_counts = {}

    for row in final_rows:
        campus_counts[row["CampusMatched"]] = campus_counts.get(row["CampusMatched"], 0) + 1
        program_counts[row["ProgramInferred"]] = program_counts.get(row["ProgramInferred"], 0) + 1

    print("\nBy campus:")
    for campus, count in sorted(campus_counts.items(), key=lambda x: x[1], reverse=True):
        print(f"  - {campus}: {count}")

    print("\nBy inferred program:")
    for program, count in sorted(program_counts.items(), key=lambda x: x[1], reverse=True):
        print(f"  - {program}: {count}")


if __name__ == "__main__":
    main()