def save_to_csv(filename: str, rows: List[dict]) -> None:
    if not rows:
        print("[INFO] No rows found.")
        return

    fieldnames = [
        "Year",
        "CampusMatched",
        "CampusMatchedConfidence",
        "ProgramInferred",
        "Title",
        "Researchers",
        "Venue",
        "Publisher",
        "Type",
        "DOI",
        "URL",
        "MatchedAffiliation",
        "AllAffiliations",
        "Subjects",
        "Abstract",
        "CrossrefQueryUsed",
    ]

    with open(filename, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"[DONE] Saved {len(rows)} rows to '{filename}'")


