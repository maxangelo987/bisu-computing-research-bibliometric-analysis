def build_session() -> requests.Session:
    session = requests.Session()

    retry = Retry(
        total=5,
        connect=5,
        read=5,
        backoff_factor=1.5,
        status_forcelist=[429, 500, 502, 503, 504],
        allowed_methods=["GET"],
        raise_on_status=False,
    )

    adapter = HTTPAdapter(max_retries=retry)
    session.mount("https://", adapter)
    session.mount("http://", adapter)

    session.headers.update({
        "User-Agent": f"{MAILTO} (BISU computing research Crossref harvester)",
        "Accept": "application/json",
    })

    return session


def normalize_text(text: Optional[str]) -> str:
    if not text:
        return ""
    text = html.unescape(text).lower()
    text = re.sub(r"<[^>]+>", " ", text)
    text = re.sub(r"[-_/(),.;:]", " ", text)
    text = re.sub(r"\bphl\b", "philippines", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def clean_text(text: Optional[str]) -> str:
    if not text:
        return ""
    text = html.unescape(text)
    text = re.sub(r"<[^>]+>", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def extract_year(item: dict) -> Optional[int]:
    date_fields = [
        item.get("published-print"),
        item.get("published-online"),
        item.get("issued"),
        item.get("created"),
    ]
    for field in date_fields:
        try:
            return int(field["date-parts"][0][0])
        except Exception:
            continue
    return None


def extract_title(item: dict) -> str:
    title = ""
    subtitle = ""

    if item.get("title"):
        title = " ".join([t for t in item["title"] if t]).strip()

    if item.get("subtitle"):
        subtitle = " ".join([s for s in item["subtitle"] if s]).strip()

    if title and subtitle:
        return f"{title}: {subtitle}"
    return title or subtitle or ""


def extract_venue(item: dict) -> str:
    event_name = ""
    if isinstance(item.get("event"), dict):
        event_name = item.get("event", {}).get("name", "") or ""

    container_title = ""
    if item.get("container-title"):
        container_title = " | ".join([c for c in item["container-title"] if c]).strip()

    publisher = (item.get("publisher") or "").strip()

    for candidate in [event_name, container_title, publisher]:
        if candidate:
            return candidate

    return "Unknown venue"


def extract_authors_and_affiliations(item: dict) -> Tuple[str, List[str]]:
    author_names = []
    affiliations = []

    for author in item.get("author", []):
        given = (author.get("given") or "").strip()
        family = (author.get("family") or "").strip()
        literal = (author.get("name") or "").strip()

        full_name = literal if literal else f"{given} {family}".strip()
        if full_name:
            author_names.append(full_name)

        for aff in author.get("affiliation", []) or []:
            aff_name = (aff.get("name") or "").strip()
            if aff_name:
                affiliations.append(aff_name)

    return ", ".join(author_names), affiliations


def match_bisu_campus(affiliations: List[str]) -> Tuple[Optional[str], Optional[str], str]:
    normalized_affiliations = [normalize_text(a) for a in affiliations if a]

    ordered_campuses = [
        "Main Campus",
        "Balilihan Campus",
        "Bilar Campus",
        "Calape Campus",
        "Candijay Campus",
        "Clarin Campus",
        "BISU (campus unspecified)",
    ]

    for campus in ordered_campuses:
        aliases = BISU_ALIAS_MAP.get(campus, [])
        for aff_raw, aff_norm in zip(affiliations, normalized_affiliations):
            for alias in aliases:
                if normalize_text(alias) in aff_norm:
                    return campus, aff_raw, "high"

    for campus, rule_groups in CAMPUS_TOKEN_RULES.items():
        for aff_raw, aff_norm in zip(affiliations, normalized_affiliations):
            for tokens in rule_groups:
                if all(token in aff_norm for token in tokens):
                    return campus, aff_raw, "medium"

    for aff_raw, aff_norm in zip(affiliations, normalized_affiliations):
        if "bohol island state university" in aff_norm or re.search(r"\bbisu\b", aff_norm):
            return "BISU (campus unspecified)", aff_raw, "low"

    return None, None, "none"


def infer_program(item: dict, affiliations: List[str]) -> str:
    title = extract_title(item)
    subjects = " ".join(item.get("subject", []) or [])
    container = " ".join(item.get("container-title", []) or [])
    publisher = item.get("publisher", "") or ""
    event_name = ""
    if isinstance(item.get("event"), dict):
        event_name = item.get("event", {}).get("name", "") or ""

    blob = normalize_text(
        f"{title} {subjects} {container} {publisher} {event_name} {' '.join(affiliations)}"
    )

    scores = {program: 0 for program in PROGRAM_RULES.keys()}

    for program, patterns in PROGRAM_RULES.items():
        for pattern in patterns:
            if pattern in blob:
                scores[program] += 1

    best_program = max(scores, key=scores.get)
    if scores[best_program] > 0:
        return best_program

    return "Computing (unspecified)"


def is_computing_record(item: dict, affiliations: List[str]) -> bool:
    title = extract_title(item)
    subjects = " ".join(item.get("subject", []) or [])
    container = " ".join(item.get("container-title", []) or [])
    publisher = item.get("publisher", "") or ""
    event_name = ""
    if isinstance(item.get("event"), dict):
        event_name = item.get("event", {}).get("name", "") or ""

    blob = normalize_text(
        f"{title} {subjects} {container} {publisher} {event_name} {' '.join(affiliations)}"
    )

    for kw in COMPUTING_KEYWORDS:
        if kw in blob:
            return True

    for hint in COMPUTING_AFFILIATION_HINTS:
        if hint in blob:
            return True

    return False


def dedup_key(row: dict) -> str:
    doi = (row.get("DOI") or "").strip().lower()
    if doi:
        return f"doi::{doi}"

    title = normalize_text(row.get("Title", ""))
    year = str(row.get("Year", ""))
    return f"title::{title}::year::{year}"


def get_total_results(
    session: requests.Session,
    affiliation_query: str,
    start_year: int,
    end_year: int,
) -> int:
    params = {
        "query.affiliation": affiliation_query,
        "filter": f"from-pub-date:{start_year}-01-01,until-pub-date:{end_year}-12-31",
        "rows": 0,
        "mailto": MAILTO,
    }

    response = session.get(CROSSREF_URL, params=params, timeout=60)

    if response.status_code != 200:
        print(f"[ERROR] count query='{affiliation_query}' status={response.status_code}")
        return -1

    payload = response.json()
    return payload.get("message", {}).get("total-results", -1)


